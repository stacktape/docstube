  '```ts',
  'type VerifierDefinition = {',
  '  id: string;',
  '  title: string;',
  '  description?: string | undefined;',
  "  scope: 'block' | 'page' | 'site';",
  '  appliesTo?: { blockTypes?: string[] | undefined; languages?: string[] | undefined } | undefined;',
  "  localeScope: 'source-only' | 'per-locale';",
  '  proves: boolean;',
  '  verify: (ctx: VerifierContext, pages: PageArtifact[]) => Promise<VerifierRunResult>;',
  '};',
  '```',
  '',
  '### Field semantics',
  '',
  '- `id` — unique verifier id; also the value of `findings[].check`. `docstube check` kinds derive from',
  '  registered verifier ids, so users can run yours directly.',
  "- `scope` — `'block'` and `'page'` verifiers run during per-page verification; `'site'` verifiers run",
  '  only in the site-wide topology pass, over ALL pages at once (cross-page links, orphans,',
  '  contradictions). In every case `verify` receives an array of `PageArtifact`s — scope controls when',
  '  and with which batch the host calls you.',
  '- `appliesTo` — a skip filter. If no block in the batch matches (`blockTypes` against',
