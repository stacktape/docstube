  '## The manifest',
  '',
  '`definePlugin` takes the manifest fields plus a `register` function:',
  '',
  '| Field | Type | Rules |',
  '| --- | --- | --- |',
  '| `apiVersion` | `1` (literal) | Required. Integer plugin API version. Loading a plugin with an unsupported version is a clean error. |',
  '| `name` | `string` | Required. npm-style name (scoped names allowed). Shared plugins use the `docstube-plugin-<x>` convention; local plugins may use any valid name. |',
  '| `version` | `string` | Required. Semver (`0.1.0`). Recorded in verification provenance. |',
  '| `description` | `string` | Optional. Shown to the user when the plugin is introduced. |',
  '| `permissions` | object | Optional; defaults to `{ network: false, exec: [], writableRoots: [] }`. See below. |',
  '| `capabilities` | array | Required, at least one entry: `{ kind, ids }` with at least one id. Declares what `register()` will add. |',
  '',
  '### Permissions semantics',
  '',
  '- `network: boolean` — whether the plugin intends to make network calls. Declared and shown to the',
  '  user at first run; not technically sandboxed in v1 (honest-but-soft, npm-style trust posture).',
