// Source text of the docs MCP server emitted into every generated site (PRODUCT §4.1: tool names
// follow the DeepWiki de-facto conventions over Streamable HTTP). The script is self-contained —
// node: builtins only — because generated sites never depend on @docstube/* packages at runtime.
//
// Streamable HTTP here means the stateless mode of the MCP Streamable HTTP transport: a single
// POST endpoint speaking JSON-RPC 2.0 (initialize / tools/list / tools/call), notifications
// acknowledged with 202, no SSE stream and no session state. That is the simplest conforming
// shape and is all a static docs site needs.

export const docsMcpServerMjs = (): string =>
  [
    '#!/usr/bin/env node',
    '// Generated by docstube — self-contained docs MCP server (Streamable HTTP, stateless mode).',
    '// Tools follow the DeepWiki de-facto names: read_wiki_structure, read_wiki_contents, ask_question.',
    '// Usage: node mcp/docs-mcp-server.mjs --port 3333',
    "import { readFile } from 'node:fs/promises';",
    "import { createServer } from 'node:http';",
    "import { dirname, join } from 'node:path';",
    "import { fileURLToPath } from 'node:url';",
    '',
    'const scriptDir = dirname(fileURLToPath(import.meta.url));',
    "const siteRoot = join(scriptDir, '..');",
    "const siteIndex = JSON.parse(await readFile(join(scriptDir, 'site-index.json'), 'utf8'));",
    'const pageBySlug = new Map(siteIndex.pages.map((page) => [page.slug, page]));',
    '',
    'const argv = process.argv.slice(2);',
    "const portFlagIndex = argv.indexOf('--port');",
    'const port = portFlagIndex === -1 ? 3333 : Number(argv[portFlagIndex + 1]);',
    '',
    "const stripFrontmatter = (markdown) => markdown.replace(/^---\\r?\\n[\\s\\S]*?\\r?\\n---\\r?\\n?/u, '');",
    '',
    '// Slugs are validated against the emitted index, so no path traversal is possible.',
    'const readPageMarkdown = async (slug) => {',
    '  if (!pageBySlug.has(slug)) {',
    '    return undefined;',
    '  }',
    "  return readFile(join(siteRoot, 'public', ...slug.split('/')) + '.md', 'utf8');",
    '};',
    '',
    'const tools = [',
    '  {',
    "    name: 'read_wiki_structure',",
    "    description: 'List the documentation pages of this site (titles, slugs, URLs).',",
    "    inputSchema: { type: 'object', properties: {} }",
    '  },',
    '  {',
    "    name: 'read_wiki_contents',",
    "    description: 'Read one documentation page as raw markdown. Pass a slug from read_wiki_structure.',",
    '    inputSchema: {',
    "      type: 'object',",
    "      properties: { page: { type: 'string', description: 'Page slug, e.g. \"getting-started/installation\".' } },",
    "      required: ['page']",
    '    }',
    '  },',
    '  {',
    "    name: 'ask_question',",
    '    description:',
    "      'Find the documentation page most relevant to a question (keyword search, not an AI answer). Hosted Ask-AI is a docstube Cloud feature.',",
    "    inputSchema: { type: 'object', properties: { question: { type: 'string' } }, required: ['question'] }",
    '  }',
    '];',
    '',
    "const textResult = (text) => ({ content: [{ type: 'text', text }] });",
    "const toolError = (text) => ({ content: [{ type: 'text', text }], isError: true });",
    '',
    'const callTool = async (name, args) => {',
    "  if (name === 'read_wiki_structure') {",
    "    const lines = siteIndex.pages.map((page) => '- ' + page.title + ' (slug: ' + page.slug + ', url: ' + page.url + ')');",
    "    return textResult('# ' + siteIndex.site + '\\n\\n' + lines.join('\\n'));",
    '  }',
    "  if (name === 'read_wiki_contents') {",
    "    const slug = String(args.page ?? '');",
    '    const markdown = await readPageMarkdown(slug);',
    '    if (markdown === undefined) {',
    "      return toolError('unknown page: ' + slug + ' — call read_wiki_structure for valid slugs');",
    '    }',
    '    return textResult(markdown);',
    '  }',
    "  if (name === 'ask_question') {",
    '    // v1 honest behavior: naive keyword scoring over titles + content. This server never fakes',
    '    // an LLM answer; it returns the best-matching page and says so.',
    "    const question = String(args.question ?? '').toLowerCase();",
    '    const terms = question.split(/[^a-z0-9]+/u).filter((term) => term.length > 2);',
    '    if (terms.length === 0) {',
    "      return toolError('ask_question needs a non-empty question');",
    '    }',
    '    let best;',
    '    for (const page of siteIndex.pages) {',
    "      const markdown = stripFrontmatter((await readPageMarkdown(page.slug)) ?? '');",
    '      const haystack = markdown.toLowerCase();',
    '      const title = page.title.toLowerCase();',
    '      let score = 0;',
    '      for (const term of terms) {',
    '        if (title.includes(term)) {',
    '          score += 5;',
    '        }',
    '        score += haystack.split(term).length - 1;',
    '      }',
    '      if (score > 0 && (best === undefined || score > best.score)) {',
    '        best = { page, markdown, score };',
    '      }',
    '    }',
    '    if (best === undefined) {',
    "      return textResult('No page matched that question. Call read_wiki_structure to browse the docs.');",
    '    }',
    '    const note =',
    "      'Note: this is keyword matching by the local docs MCP server, not an AI-generated answer. Hosted Ask-AI is a docstube Cloud feature.';",
    "    return textResult(note + '\\n\\n# ' + best.page.title + ' (' + best.page.url + ')\\n\\n' + best.markdown);",
    '  }',
    '  return undefined;',
    '};',
    '',
    'const rpcError = (code, message) => Object.assign(new Error(message), { rpcCode: code });',
    '',
    'const handleRequest = async (message) => {',
    "  if (message.method === 'initialize') {",
    '    return {',
    "      protocolVersion: '2025-03-26',",
    '      capabilities: { tools: {} },',
    "      serverInfo: { name: 'docstube-docs-mcp', version: siteIndex.generatorVersion }",
    '    };',
    '  }',
    "  if (message.method === 'ping') {",
    '    return {};',
    '  }',
    "  if (message.method === 'tools/list') {",
    '    return { tools };',
    '  }',
    "  if (message.method === 'tools/call') {",
    '    const result = await callTool(message.params?.name, message.params?.arguments ?? {});',
    '    if (result === undefined) {',
    "      throw rpcError(-32602, 'unknown tool: ' + message.params?.name);",
    '    }',
    '    return result;',
    '  }',
    "  throw rpcError(-32601, 'method not supported: ' + message.method);",
    '};',
    '',
    'const respond = (response, status, payload) => {',
    "  response.writeHead(status, { 'content-type': 'application/json' });",
    '  response.end(JSON.stringify(payload));',
    '};',
    '',
    'const server = createServer((request, response) => {',
    "  if (request.method !== 'POST') {",
    "    response.writeHead(405, { allow: 'POST' });",
    '    response.end();',
    '    return;',
    '  }',
    "  let body = '';",
    "  request.setEncoding('utf8');",
    "  request.on('data', (chunk) => {",
    '    body += chunk;',
    '  });',
    "  request.on('end', async () => {",
    '    let message;',
    '    try {',
    '      message = JSON.parse(body);',
    '    } catch {',
    "      respond(response, 400, { jsonrpc: '2.0', id: null, error: { code: -32700, message: 'parse error' } });",
    '      return;',
    '    }',
    '    // Notifications (no id) are acknowledged with 202 and no body, per Streamable HTTP.',
    '    if (message.id === undefined || message.id === null || message.method === undefined) {',
    '      response.writeHead(202);',
    '      response.end();',
    '      return;',
    '    }',
    '    try {',
    '      const result = await handleRequest(message);',
    "      respond(response, 200, { jsonrpc: '2.0', id: message.id, result });",
    '    } catch (error) {',
    '      respond(response, 200, {',
    "        jsonrpc: '2.0',",
    '        id: message.id,',
    '        error: { code: error.rpcCode ?? -32603, message: error.message }',
    '      });',
    '    }',
    '  });',
    '});',
    '',
    "server.listen(port, '127.0.0.1', () => {",
    "  console.info('docs-mcp-server listening on http://127.0.0.1:' + server.address().port);",
    '});',
    ''
  ].join('\n');

