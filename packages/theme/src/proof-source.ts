// Section claim-count chips: headings get github-slugger ids from Astro, matching the section
// anchors in the manifest. Literal counts only; a contradicted section is marked loudly.
// Progressive enhancement — missing anchors no-op.
export const docstubeSectionChipsAstro = (): string =>
  [
    '---',
    '// Generated by docstube (kernel-owned) — injects per-section claim-count chips by anchor.',
    'const { sections = [] } = Astro.props;',
    '---',
    '',
    '{sections.length > 0 ? (',
    '  <script type="application/json" id="dt-section-claims" set:html={JSON.stringify(sections)} />',
    ') : null}',
    '<script is:inline>',
    '  (() => {',
    "    const data = document.getElementById('dt-section-claims');",
    '    if (!data) return;',
    '    for (const section of JSON.parse(data.textContent)) {',
    '      if (!section.total) continue;',
    '      const heading = document.getElementById(section.anchor);',
    '      if (!heading) continue;',
    "      const chip = document.createElement('span');",
    '      const contradicted = section.contradicted > 0;',
    "      chip.className = 'dt-claims dt-section-chip' + (contradicted ? ' dt-section-chip--contradicted' : '');",
    '      chip.dataset.docstubeClaimsChecked = String(section.checked);',
    '      chip.dataset.docstubeClaimsTotal = String(section.total);',
    '      chip.dataset.docstubeClaimsContradicted = String(section.contradicted);',
    '      chip.textContent = contradicted',
    "        ? '\\u26a0 ' + section.contradicted + ' contradicted'",
    "        : section.checked + '/' + section.total + ' checked';",
    "      heading.append(' ', chip);",
    '    }',
    '  })();',
    '</script>',
    ''
  ].join('\n');

