// Source text of the kernel-owned src/docstube/** modules emitted into every generated site.
// Proof rendering is a conformance contract, not a theme choice (knowledge/design/theming.md):
// every theme layout must mount these primitives; themes style them but never decide whether they
// exist. Self-contained — generated sites never depend on @docstube/* packages at runtime.
//
// The rendered vocabulary is LITERAL (impl-07 finding 4): claim counts ("N of M claims checked"),
// an explicit contradiction warning, per-claim contradicted marks, and "reviewed for <persona>"
// ONLY when a primary review genuinely completed. The guarantee-label ladder
// ('proven'/'scored'/'verified'-by-fallback) is gone from the public surface.

// Claims chip: the literal checked/total count plus the honestly-earned editorial label. A page
// whose shard carries no trust spine at all renders a LOUD warning chip instead of a silent 0/0
// (impl-08): the reader must see that this page could not be verified. A source-fallback
// rendition (i18n-lifecycle-v2 decision 1: a locale route serving the source content because its
// translation failed or is pending) renders a visible not-yet-translated notice — the translation
// dimension, separate from source correctness (decision 3).
//
// TWO DIMENSIONS, NEVER COLLAPSED (decision 3): a served rendition inherits the canonical page's
// checked counts, because claim correctness is language-independent — but that says nothing about
// whether the TRANSLATION preserved meaning. The translation-assurance line states that
// separately, next to the counts. The bilingual fidelity review that would move a page to
// "reviewed" (decision 2) is implemented in the i18n wave; until then every shipped translation
// says "not yet reviewed", which is the honest interim surface for an unbuilt feature.
export const docstubeClaimsAstro = (): string =>
  [
    '---',
    '// Generated by docstube (kernel-owned) — the literal claims chip every theme mounts.',
    'const { checked = 0, total = 0, contradicted = 0, uncovered = 0, complete = false, reviewedFor, unverifiedPage = false, sourceFallback = false, dirtyWorkingTree = false, translationAssurance, class: className } = Astro.props;',
    '// NO HIDDEN DENOMINATOR (PRODUCT §1.2): `uncovered` counts assertion-shaped sentences the',
    '// coverage linter found outside every <Claim> marker. The complete state is gated on it, so a',
    '// page can never read as done by simply leaving its facts unmarked.',
    '// DEFENSIVE RECOMPUTE (impl-24): the chip never trusts the `complete` flag alone. It re-derives',
    '// the state from the very numbers it renders, so a stale build, a hand-edited artifact, or a',
    '// frontmatter key that survived from somewhere else can never paint a partial page green.',
    '// A DIRTY WORKING TREE CANNOT MINT THE COMPLETE STATE (PRODUCT §1.2): the run read bytes that',
    '// exist in no commit, and the badge is a claim about COMMITTED source. The counts are genuine',
    '// (content-hash bound) and stay visible; only the claim degrades — the note below says so, and',
    '// the green/complete styling is never applied. The recompute enforces it here too, so a stale',
    '// build or a hand-edited artifact cannot paint an uncommitted run green.',
    'const isComplete = complete === true && dirtyWorkingTree !== true && total > 0 && checked === total && uncovered === 0 && contradicted === 0;',
    'const chipClasses = ["dt-claims", isComplete ? "dt-claims--complete" : null, className].filter(Boolean).join(" ");',
    '// HONEST BADGE SEMANTICS (PRODUCT §1.2, harness-state-v2 decisions 4-5): the complete state is',
    "// a statement about this page's LEDGER plus a deterministic detector, not a soundness proof",
    "// over its prose. Detecting every factual assertion needs semantics, which is the risk critic's",
    '// job. The popover says exactly that, so no reader can read green as "nothing here is unverified".',
    'const completeMeaning =',
    '  "Complete means: every claim in this page\'s ledger is checked, and no unmarked assertion was detected. " +',
    '  "It does not mean the page contains no unverified statement \\u2014 automatic detection of unmarked claims is a floor, not a proof.";',
    'const chipTitle = isComplete',
    '  ? completeMeaning',
    '  : dirtyWorkingTree',
    '    ? "This page was checked against uncommitted changes in the working tree, so no commit contains the checked source. The counts are real; the complete state is withheld until the source is committed and the page regenerated."',
    '    : uncovered > 0',
    '      ? "This page has assertion-shaped sentences that no claim marker covers, so it cannot be complete."',
    '      : "Not every claim in this page\'s ledger is checked.";',
    '// Translation assurance is its OWN dimension — never folded into the checked counts.',
    'const translationLabel = {',
    '  "not-reviewed": "Translation: not yet reviewed",',
    '  reviewed: "Translation: fidelity reviewed"',
    '}[translationAssurance];',
    '---',
    '',
    '<span class="dt-claims-chips">',
    '  {unverifiedPage ? (',
    '    <span class="dt-unverified-warning" role="status" data-docstube-unverified="true">',
    "      {'\\u26a0'} This page could not be verified",
    '    </span>',
    '  ) : null}',
    '  {sourceFallback ? (',
    '    <span class="dt-source-fallback" role="status" data-docstube-source-fallback="true">',
    '      Not yet translated — showing the original-language content',
    '    </span>',
    '  ) : null}',
    '  {total > 0 || uncovered > 0 ? (',
    '    <span class={chipClasses} title={chipTitle} data-docstube-claims-checked={checked} data-docstube-claims-total={total} data-docstube-uncovered-assertions={uncovered} data-docstube-claims-complete={isComplete ? "true" : "false"}>',
    '      {total > 0 ? `${checked} of ${total} claims checked` : "no claims recorded"}',
    '      {uncovered > 0 ? ` \\u00b7 ${uncovered} unmarked assertion${uncovered === 1 ? "" : "s"}` : ""}',
    '    </span>',
    '  ) : null}',
    '  {dirtyWorkingTree ? (',
    '    <span class="dt-uncommitted" role="status" data-docstube-dirty-working-tree="true">',
    '      checked against uncommitted changes',
    '    </span>',
    '  ) : null}',
    '  {translationLabel ? (',
    '    <span class="dt-translation-assurance" role="status" data-docstube-translation-assurance={translationAssurance}>',
    '      {translationLabel}',
    '    </span>',
    '  ) : null}',
    '  {reviewedFor ? (',
    '    <span class="dt-reviewed" data-docstube-reviewed-for={reviewedFor}>reviewed for {reviewedFor}</span>',
    '  ) : null}',
    '</span>',
    ''
  ].join('\n');

// Contradiction + unchecked surface: a loud page-level warning banner plus per-claim contradicted
// marks on the inline <Claim> elements (matched by marker id). Rendered IMMEDIATELY — a caught lie
// must never read as ordinary content. UNCHECKED claims get a QUIET-but-visible mark (impl-09
// finding 2): dotted underline + title — an exception indicator, visually lighter than a
// contradiction, never an alarm. The inline mark script is PARSE-SAFE (impl-10 finding 3): themes
// mount this primitive before the content slot, so it defers its DOM queries to DOMContentLoaded
// when the document is still parsing.
export const docstubeContradictionsAstro = (): string =>
  [
    '---',
    '// Generated by docstube (kernel-owned) — the contradiction warning every theme mounts.',
    'const { contradicted = 0, markers = [], uncheckedMarkers = [] } = Astro.props;',
    '---',
    '',
    '{contradicted > 0 ? (',
    '  <div class="dt-contradictions" role="alert" data-docstube-contradicted={contradicted}>',
    "    {'\\u26a0'} {contradicted} claim{contradicted === 1 ? '' : 's'} on this page {contradicted === 1 ? 'is' : 'are'} contradicted by the source. Treat the marked statements as wrong until regenerated.",
    '  </div>',
    ') : null}',
    '{markers.length > 0 ? (',
    '  <script type="application/json" id="dt-contradicted-claims" set:html={JSON.stringify(markers)} />',
    ') : null}',
    '{uncheckedMarkers.length > 0 ? (',
    '  <script type="application/json" id="dt-unchecked-claims" set:html={JSON.stringify(uncheckedMarkers)} />',
    ') : null}',
    '<script is:inline>',
    '  (() => {',
    '    // Parse-safe timing (impl-10 finding 3): themes mount this primitive BEFORE the',
    '    // <Claim>-bearing content slot, so the marks must wait until the DOM finished parsing —',
    '    // querying immediately would find none of its targets and silently mark nothing.',
    '    const applyClaimMarks = () => {',
    "      const data = document.getElementById('dt-contradicted-claims');",
    '      if (data) {',
    '        for (const markerId of JSON.parse(data.textContent)) {',
    '          const claim = document.querySelector(`[data-docstube-claim="${markerId}"]`);',
    '          if (!claim) continue;',
    "          claim.classList.add('dt-claim--contradicted');",
    "          claim.dataset.docstubeContradicted = 'true';",
    "          const mark = document.createElement('span');",
    "          mark.className = 'dt-claim-mark';",
    "          mark.textContent = '\\u26a0 contradicted';",
    "          claim.append(' ', mark);",
    '        }',
    '      }',
    "      const unchecked = document.getElementById('dt-unchecked-claims');",
    '      if (unchecked) {',
    '        for (const markerId of JSON.parse(unchecked.textContent)) {',
    '          const claim = document.querySelector(`[data-docstube-claim="${markerId}"]`);',
    '          // A contradicted mark always wins over the quiet unchecked mark.',
    "          if (!claim || claim.dataset.docstubeContradicted === 'true') continue;",
    "          claim.classList.add('dt-claim--unchecked');",
    "          claim.dataset.docstubeUnchecked = 'true';",
    "          claim.setAttribute('title', 'This statement has not been mechanically checked against the source.');",
    '        }',
    '      }',
    '    };',
    "    if (document.readyState === 'loading') {",
    "      document.addEventListener('DOMContentLoaded', applyClaimMarks, { once: true });",
    '    } else {',
    '      applyClaimMarks();',
    '    }',
    '  })();',
    '</script>',
    ''
  ].join('\n');

