// Provenance sources footer: per-entity citations, linkified when the repo URL is known.
//
// NO UNVOUCHED COMMIT ON A READER SURFACE (wave 2b close — the spine finding): when the run read
// UNCOMMITTED changes, the recorded commit is HEAD, and HEAD did not contain the bytes that were
// checked. Presenting it — as a label or as a /blob/<commit> link to prose that differs from what
// was read — would attribute this page's evidence to a revision that cannot vouch for it. The
// commit is withheld and the same uncommitted-tree wording the chip uses takes its place.
export const docstubeSourcesAstro = (): string =>
  [
    '---',
    '// Generated by docstube (kernel-owned) — the provenance sources footer every theme mounts.',
    'const { sources = [], repoUrl, dirtyWorkingTree = false } = Astro.props;',
    'const sourceHref = (source) =>',
    '  repoUrl && !dirtyWorkingTree',
    "    ? `${repoUrl.replace(/\\/$/, '')}/blob/${source.commit}/${source.file}${source.line ? `#L${source.line}` : ''}`",
    '    : undefined;',
    '---',
    '',
    '{sources.length > 0 ? (',
    '  <footer class="dt-sources" data-docstube-sources>',
    '    <h2>Sources</h2>',
    '    {dirtyWorkingTree ? (',
    '      <p class="dt-uncommitted" role="status" data-docstube-dirty-working-tree="true">',
    '        checked against uncommitted changes — no commit contains the source this page was checked against',
    '      </p>',
    '    ) : null}',
    '    <ul>',
    '      {sources.map((source) => {',
    '        const label = source.line ? `${source.file}:${source.line}` : source.file;',
    '        const href = sourceHref(source);',
    '        return (',
    '          <li>',
    '            {href ? (',
    '              <a href={href}>',
    '                <code>{label}</code>',
    '              </a>',
    '            ) : (',
    '              <code>{label}</code>',
    '            )}',
    '            {dirtyWorkingTree ? null : <span class="dt-source-commit">@{source.commit.slice(0, 7)}</span>}',
    '          </li>',
    '        );',
    '      })}',
    '    </ul>',
    '  </footer>',
    ') : null}',
    ''
  ].join('\n');

