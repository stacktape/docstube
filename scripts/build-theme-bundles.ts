// Compiles every theme source directory (packages/theme/src/themes/<name>/) into its checked-in
// bundle.generated.ts: site/** files become emitted-site 'src/**' text entries (LF-normalized),
// assets/** files become 'public/**' base64 entries. Run via `node scripts/build-theme-bundles.ts`
// (wired as the packages/theme build prestep); themes/bundle-sync.spec.ts asserts the generated
// modules stay in sync with the source trees.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const themesDir = join(scriptsDir, '..', 'packages', 'theme', 'src', 'themes');

type GeneratedFile = { path: string; content: string } | { path: string; base64: string };

const walkFiles = async (root: string, relative = ''): Promise<string[]> => {
  let entries;
  try {
    entries = await readdir(join(root, relative), { withFileTypes: true });
  } catch {
    return [];
  }
  const files: string[] = [];
  for (const entry of entries) {
    const entryPath = relative === '' ? entry.name : `${relative}/${entry.name}`;
    if (entry.isDirectory()) {
      files.push(...(await walkFiles(root, entryPath)));
    } else {
      files.push(entryPath);
    }
  }
  return files;
};

// oxfmt-compatible string literal: single quotes unless the content has fewer double quotes.
const toStringLiteral = (value: string): string => {
  const singles = (value.match(/'/g) ?? []).length;
  const doubles = (value.match(/"/g) ?? []).length;
  const quote = singles > doubles ? '"' : "'";
  const escaped = value
    .replaceAll('\\', '\\\\')
    .replaceAll(quote, `\\${quote}`)
    .replaceAll('\n', '\\n')
    .replaceAll('\r', '\\r')
    .replaceAll('\t', '\\t');
  return `${quote}${escaped}${quote}`;
};

const collectThemeFiles = async (themeDir: string): Promise<GeneratedFile[]> => {
  const files: GeneratedFile[] = [];
  const siteFiles = await walkFiles(join(themeDir, 'site'));
  for (const relative of siteFiles) {
    const raw = await readFile(join(themeDir, 'site', relative), 'utf8');
    files.push({ path: `src/${relative}`, content: raw.replace(/\r\n/g, '\n') });
  }
  const assetFiles = await walkFiles(join(themeDir, 'assets'));
  for (const relative of assetFiles) {
    const raw = await readFile(join(themeDir, 'assets', relative));
    files.push({ path: `public/${relative}`, base64: raw.toString('base64') });
  }
  return files.toSorted((left, right) => left.path.localeCompare(right.path));
};

const generatedModule = (files: GeneratedFile[]): string => {
  const entries = files.map((file) => {
    const value =
      'content' in file ? `content: ${toStringLiteral(file.content)}` : `base64: ${toStringLiteral(file.base64)}`;
    return `    { path: ${toStringLiteral(file.path)}, ${value} }`;
  });
  return [
    '// GENERATED by scripts/build-theme-bundles.ts from the sibling site/ and assets/ directories.',
    '// Do not edit by hand — edit the source files and rerun `node scripts/build-theme-bundles.ts`.',
    '// themes/bundle-sync.spec.ts asserts this module matches the source tree byte for byte.',
    "import type { ThemeBundle } from '../../theme-manifest.ts';",
    "import { manifest } from './theme.ts';",
    '',
    'export const themeBundle: ThemeBundle = {',
    '  manifest,',
    '  files: [',
    entries.join(',\n'),
    '  ]',
    '};',
    ''
  ].join('\n');
};

const main = async (): Promise<void> => {
  const themeNames = (await readdir(themesDir, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .toSorted();
  for (const name of themeNames) {
    const themeDir = join(themesDir, name);
    const files = await collectThemeFiles(themeDir);
    if (files.length === 0) {
      throw new Error(`theme "${name}" has no site/ or assets/ files to bundle`);
    }
    const outPath = join(themeDir, 'bundle.generated.ts');
    await writeFile(outPath, generatedModule(files), 'utf8');
    console.info(`bundled theme "${name}" (${files.length} file(s)) -> ${outPath}`);
  }
};

await main();
