import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { AgentTaskSpec, Codemap, Transcript } from '@docstube/contracts';
import { buildCodemap } from '@docstube/codemap';
import { typescriptLanguagePack } from '@docstube/lang-typescript';
import { runGenerate, type GenerateSummary } from '@docstube/core';

// Dogfood: docstube documents a real slice of itself (the contracts package) through the actual
// pipeline — real codemap, real verifiers, real gate — with a DETERMINISTIC writer so CI never
// calls a live model. A staged scratch workspace keeps the real repo's .docstube/ untouched.

const repoRoot = resolve(fileURLToPath(new URL('.', import.meta.url)), '..', '..');

const dogfoodConfig = `schemaVersion: 1
docType: external-library
projectContext: The docstube contracts package — the S0 schema layer of docstube itself.
personas:
  - id: plugin-author
    description: Builds docstube plugins against the public contracts
site:
  title: docstube contracts (dogfood)
`;

const dogfoodIa = `schemaVersion: 1
tree:
  - title: Overview
    slug: overview
    brief: What the contracts package contains and how the entity model fits together.
  - title: Guarantee levels
    slug: guarantee-levels
    brief: The proven / scored / out-of-domain taxonomy and how roll-up works.
`;

// Deterministic writer: renders MDX from the codemap. No model, no network — same input, same
// docs. This is the dogfood stand-in for the write stage; verified by the real verifiers.
export const deterministicWriter =
  (codemap: Codemap) =>
  async (spec: AgentTaskSpec): Promise<Transcript> => {
    if (spec.kind === 'audit-extract-claims') {
      return {
        schemaVersion: 1,
        taskId: spec.id,
        cacheKey: 'dogfood-deterministic',
        transport: 'replay',
        model: 'deterministic-dogfood',
        turns: [],
        observedReads: [],
        usage: { inputTokens: 0, outputTokens: 0, cacheHit: false },
        stopReason: 'complete',
        result: { type: 'structured', value: { claims: [] } }
      };
    }
    if (spec.kind === 'review-page') {
      const personaMatch = spec.systemPrompt.match(/one persona: ([a-z0-9-]+)/);
      return {
        schemaVersion: 1,
        taskId: spec.id,
        cacheKey: 'dogfood-deterministic',
        transport: 'replay',
        model: 'deterministic-dogfood',
        turns: [],
        observedReads: [],
        usage: { inputTokens: 0, outputTokens: 0, cacheHit: false },
        stopReason: 'complete',
        result: {
          type: 'structured',
          value: {
            persona: personaMatch?.[1] ?? 'plugin-author',
            criteria: [
              { criterion: 'audience-fit', outcome: 'met', reasoning: 'Deterministic dogfood review — structure only.' }
            ],
            findings: []
          }
        }
      };
    }
    const slugMatch = spec.userPrompt.match(/slug: ([a-z0-9/-]+)/);
    const titleMatch = spec.userPrompt.match(/documentation page "([^"]+)"/);
    const slug = slugMatch?.[1] ?? 'page';
    const title = titleMatch?.[1] ?? slug;
    const symbols = codemap.symbols.filter((symbol) => symbol.visibility === 'public').slice(0, 8);
    const symbolList = symbols
      .map(
        (symbol) => `- \`${[...symbol.containerPath, symbol.name].join('.')}\` — ${symbol.kind} in \`${symbol.file}\``
      )
      .join('\n');
    const mdx = `---
title: ${title}
description: Deterministic dogfood page for ${slug}.
---

# ${title}

This page is generated by the docstube dogfood build from the committed codemap.

## Public surface

${symbolList}

## Example

\`\`\`ts
const guaranteeLevels = ['proven', 'scored', 'out-of-domain'] as const;
const weakest: string = guaranteeLevels[2];
\`\`\`
`;
    return {
      schemaVersion: 1,
      taskId: spec.id,
      cacheKey: 'dogfood-deterministic',
      transport: 'replay',
      model: 'deterministic-dogfood',
      turns: [{ role: 'assistant', blocks: [{ type: 'text', text: mdx }] }],
      observedReads: [],
      usage: { inputTokens: 0, outputTokens: 0, cacheHit: false },
      stopReason: 'complete',
      result: { type: 'mdx', mdx }
    };
  };

export type DogfoodBuildResult = {
  workspaceDir: string;
  summary: GenerateSummary;
};

export const buildDogfood = async (options?: { outputDir?: string }): Promise<DogfoodBuildResult> => {
  const outputDir = resolve(repoRoot, options?.outputDir ?? 'dist-dogfood');
  await rm(outputDir, { recursive: true, force: true });
  await mkdir(outputDir, { recursive: true });

  // Stage the scratch workspace: contracts source + config family.
  const workspaceDir = join(outputDir, 'workspace');
  await mkdir(join(workspaceDir, 'src'), { recursive: true });
  await cp(join(repoRoot, 'packages', 'contracts', 'src'), join(workspaceDir, 'src'), {
    recursive: true,
    filter: (source) => !source.endsWith('.spec.ts')
  });
  await writeFile(
    join(workspaceDir, 'package.json'),
    JSON.stringify({ name: 'docstube-contracts-dogfood', type: 'module' }, null, 2)
  );
  await writeFile(join(workspaceDir, 'docstube.yml'), dogfoodConfig);
  await writeFile(join(workspaceDir, 'ia.yml'), dogfoodIa);

  const commit = '0'.repeat(40);
  const codemap = await buildCodemap({ repoRoot: workspaceDir, commit, packs: [typescriptLanguagePack] });
  const summary = await runGenerate({
    repoRoot: workspaceDir,
    runTask: deterministicWriter(codemap),
    toolDescriptors: []
  });
  return { workspaceDir, summary };
};

const isDirectRun =
  process.argv[1] !== undefined && import.meta.url === new URL(`file:///${process.argv[1].replaceAll('\\', '/')}`).href;
if (isDirectRun) {
  const { summary, workspaceDir } = await buildDogfood();
  const flagged = summary.pages.filter((page) => page.status === 'flagged');
  console.info(`dogfood: ${summary.pages.length} page(s) generated into ${workspaceDir} — outcome ${summary.outcome}`);
  if (summary.outcome !== 'passed') {
    console.error(`dogfood build not clean: ${flagged.map((page) => page.slug).join(', ')} flagged`);
    process.exitCode = 1;
  }
}
