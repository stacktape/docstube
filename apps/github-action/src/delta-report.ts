import type { Flag } from '@docstube/contracts';
import type { AutoMergeDecision } from './merge-decision.ts';
import type { GuaranteeCounts, PageDelta, VerifiedDelta } from './verified-delta.ts';
import { normalizeRepoPath } from './verified-delta.ts';

// Rendering of the verified delta into the three delivery surfaces (PRODUCT decision log —
// "flag delivery: PR comment always + digest issue for tribal-knowledge questions"):
// PR body, marker-tagged PR comment, marker-tagged digest issue, and the Actions job summary.

export const flagCommentMarker = '<!-- docstube:flag-report -->';
export const digestIssueMarker = '<!-- docstube:open-questions -->';
export const digestIssueTitle = 'docstube: open questions';

const machineLocalPatterns = [/^\.docstube\/db\.sqlite/, /^\.docstube\/cache\//, /^\.docstube\/runs\//];

// Everything the run changed ships in ONE commit — docs, manifest shards, criteria, instructions,
// knowledge — so the PR carries docs + provenance + flags atomically (ARCHITECTURE §5.3). Only
// machine-local derived state is excluded (ARCHITECTURE §5.2).
export const selectCommitPaths = (changedFiles: readonly string[]): readonly string[] =>
  changedFiles
    .map(normalizeRepoPath)
    .filter((path) => !machineLocalPatterns.some((pattern) => pattern.test(path)))
    .toSorted();

export const formatEntityAddress = (flag: Flag): string | undefined =>
  flag.entity
    ? `${flag.entity.version}/${flag.entity.locale}/${flag.entity.pageId}${flag.entity.entityId ? `#${flag.entity.entityId}` : ''}`
    : undefined;

const formatFlagLine = (flag: Flag): string => {
  const address = formatEntityAddress(flag);
  const parts = [`- **${flag.kind}** — ${flag.summary}`];
  if (address) {
    parts.push(` (\`${address}\`)`);
  }
  return parts.join('');
};

const formatCounts = (counts: GuaranteeCounts): string =>
  `${counts.proven} proven · ${counts.scored} scored · ${counts['out-of-domain']} out-of-domain`;

const formatPageRow = (page: PageDelta): string =>
  `| \`${page.slug}\` (${page.locale}) | ${page.guarantees.proven} | ${page.guarantees.scored} | ${page.guarantees['out-of-domain']} | ${page.openFlags.length} |`;

const changedPagesSection = (delta: VerifiedDelta): string[] =>
  delta.changedPages.length === 0
    ? ['No page shards changed in this run.']
    : [
        '| Page | Proven | Scored | Out-of-domain | Open flags |',
        '| --- | ---: | ---: | ---: | ---: |',
        ...delta.changedPages.map(formatPageRow),
        '',
        `Totals: ${formatCounts(delta.totals)}.`
      ];

const flagsSection = (openFlags: readonly Flag[]): string[] =>
  openFlags.length === 0 ? ['No open flags. This PR is eligible for auto-merge.'] : openFlags.map(formatFlagLine);

const decisionLine = (decision: AutoMergeDecision | undefined): string => {
  if (!decision) {
    return 'Auto-merge: not attempted — no verified manifest delta was available for this run.';
  }
  return decision.autoMerge
    ? 'Auto-merge: eligible — no open flag blocks this change.'
    : `Auto-merge: blocked by ${decision.blockingFlags.length} open flag${decision.blockingFlags.length === 1 ? '' : 's'}.`;
};

export const buildPullRequestBody = (input: {
  mode: string;
  delta: VerifiedDelta | undefined;
  decision: AutoMergeDecision | undefined;
  committedPaths: readonly string[];
}): string => {
  const lines = [
    `## docstube ${input.mode}`,
    '',
    'Generated by the docstube GitHub Action. Every change below is annotated with what proves it.',
    ''
  ];
  if (input.delta) {
    lines.push('### Changed pages', '', ...changedPagesSection(input.delta), '');
    lines.push(`### Open flags (${input.delta.openFlags.length})`, '', ...flagsSection(input.delta.openFlags), '');
  } else {
    lines.push('### Verified delta', '', 'No manifest index was found, so no verified delta could be computed.', '');
  }
  lines.push('### Decision', '', decisionLine(input.decision), '');
  lines.push('### Committed files', '', ...input.committedPaths.map((path) => `- \`${path}\``));
  return lines.join('\n');
};

// Flags are the only human touchpoint (PRODUCT §3.3) — the PR comment is where they surface.
export const buildFlagCommentBody = (openFlags: readonly Flag[]): string =>
  [
    flagCommentMarker,
    '## docstube flags',
    '',
    `${openFlags.length} open flag${openFlags.length === 1 ? '' : 's'} require attention. Flags are the only human touchpoint — resolve them in the docstube dashboard flag queue or by answering below.`,
    '',
    ...openFlags.map(formatFlagLine)
  ].join('\n');

export type IssueComment = { id: number; body: string };

export type CommentUpsertPlan = { action: 'create' } | { action: 'update'; commentId: number };

// Find-and-update the single marker-tagged comment instead of spamming a new one per run.
export const planCommentUpsert = (comments: readonly IssueComment[], marker: string): CommentUpsertPlan => {
  const existing = comments.find((comment) => comment.body.includes(marker));
  return existing ? { action: 'update', commentId: existing.id } : { action: 'create' };
};

const formatDigestEntry = (flag: Flag): string => {
  const address = formatEntityAddress(flag);
  const lines = [`- ${flag.question ?? flag.summary}`];
  if (address) {
    lines.push(`  - entity: \`${address}\``);
  }
  if (flag.subjectSymbol) {
    lines.push(`  - symbol: \`${flag.subjectSymbol}\``);
  }
  lines.push(`  - flag: \`${flag.id}\``);
  return lines.join('\n');
};

// Tribal-knowledge questions additionally roll into one long-lived digest issue: ask once,
// non-blocking for generation, durable beyond merged PRs (PRODUCT §4.1 tribal-knowledge capture).
export const buildDigestIssueBody = (tribalFlags: readonly Flag[]): string =>
  [
    digestIssueMarker,
    '## Open tribal-knowledge questions',
    '',
    'docstube hit claims it cannot prove from source. Answers become durable context keyed to the symbol/entity and are incorporated on the next run. Generation never waits on these.',
    '',
    ...(tribalFlags.length === 0 ? ['No open questions right now.'] : tribalFlags.map(formatDigestEntry))
  ].join('\n');

export type JobSummaryInput = {
  mode: string;
  status: 'failed' | 'no-changes' | 'pull-request';
  autoMerge: 'enabled' | 'blocked' | 'unavailable' | 'skipped';
  delta: VerifiedDelta | undefined;
  decision: AutoMergeDecision | undefined;
  pullRequestUrl?: string | undefined;
  committedPaths: readonly string[];
  failureOutput?: string | undefined;
};

const autoMergeSummaryLine = (input: JobSummaryInput): string => {
  switch (input.autoMerge) {
    case 'enabled':
      return 'Auto-merge enabled (squash). The PR merges once required checks pass.';
    case 'blocked':
      return `Auto-merge blocked by ${input.decision && !input.decision.autoMerge ? input.decision.blockingFlags.length : 0} open flag(s); see the flag comment on the PR.`;
    case 'unavailable':
      return 'Auto-merge could not be enabled (repository setting or missing verified delta); the PR was left open.';
    case 'skipped':
      return 'Auto-merge not applicable for this run.';
  }
};

export const buildJobSummary = (input: JobSummaryInput): string => {
  const lines = [`## docstube ${input.mode}`, ''];
  if (input.status === 'failed') {
    lines.push('docstube did not complete successfully. No branch was pushed and no PR was opened.');
    if (input.failureOutput) {
      lines.push('', '```', input.failureOutput.trim(), '```');
    }
    return lines.join('\n');
  }
  if (input.status === 'no-changes') {
    lines.push('docstube completed and left no documentation changes to ship.');
    return lines.join('\n');
  }
  lines.push(`docstube opened or updated a PR: ${input.pullRequestUrl ?? 'unknown URL'}`, '');
  if (input.delta) {
    lines.push('### Verified delta', '', ...changedPagesSection(input.delta), '');
    lines.push(`### Open flags (${input.delta.openFlags.length})`, '', ...flagsSection(input.delta.openFlags), '');
  }
  lines.push('### Decision', '', autoMergeSummaryLine(input), '');
  lines.push('### Committed files', '', ...input.committedPaths.map((path) => `- \`${path}\``));
  return lines.join('\n');
};
